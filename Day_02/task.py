
## Understanding Data Types, and How to Manipulate Strings.
## Data Type 1) String, 2)Integers, 3) Floats, 4) Booleans

### Subscripting
print("Hello"[4])
print("Hello"[-1])

## String
print("123" + "345") # Concatenation

## Integer = Whole number
print(123 + 345)

## Large Integers
print(123_456_789)

## Float = Floating point number
print(3.14159)

## Boolean
print(True)
print(False)